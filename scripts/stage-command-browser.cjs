const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
async function main() {
  const base = process.env.BASE_URL || 'http://127.0.0.1:4318', output = path.resolve('previews/stage-command')
  fs.mkdirSync(output,{recursive:true})
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']})
  const page = await browser.newPage({viewport:{width:1440,height:900}}), errors=[], failed=[], checks=[]
  await page.addInitScript(() => Object.defineProperty(navigator,'gpu',{get:()=>undefined}))
  page.on('pageerror',e=>errors.push(e.message))
  page.on('requestfailed',r=>failed.push({url:r.url(),error:r.failure()?.errorText}))
  const until = async (read,accept) => { const end=Date.now()+45000; while(Date.now()<end) { const value=await read(); if(accept(value)) return value; await new Promise(r=>setTimeout(r,600)) } throw new Error('Timed out awaiting persisted scene') }
  try {
    await page.goto(base,{waitUntil:'networkidle'})
    await page.waitForTimeout(1500)
    await page.getByRole('button',{name:'开始说话 / 输入文字',exact:true}).click()
    await page.getByRole('button',{name:'试用示例',exact:true}).click()
    await page.getByRole('button',{name:'生成舞台方案',exact:true}).click()
    await page.getByRole('heading',{name:'先看台位，再确认搭台'}).waitFor()
    assert.equal(await page.locator('.stage-plan-item').count(),3)
    assert.equal(await page.getByRole('button',{name:'确认搭台',exact:true}).isEnabled(),true)
    await page.screenshot({path:path.join(output,'review.png')})
    checks.push('Offline sample produces sofa/window/door ghost and explicit defaults')
    await page.getByRole('button',{name:'确认搭台',exact:true}).click()
    await page.waitForURL('**/scene/**',{timeout:60000})
    const id=new URL(page.url()).pathname.split('/').at(-1)
    const read = async()=>{const response=await page.request.get(base+'/api/scenes/'+id);assert.equal(response.status(),200);return response.json()}
    let stored=await until(read,s=>Object.values(s.graph.nodes).filter(n=>n.metadata.stageKind).length===3)
    const objects=Object.values(stored.graph.nodes).filter(n=>n.metadata.stageKind)
    assert.deepEqual(objects.map(n=>n.metadata.stageKind).sort(),['door-flat','sofa','window-flat'])
    assert.equal(new Set(objects.map(n=>n.id)).size,3)
    checks.push('Confirmed plan applies through normal scene store and persists exactly three objects')
    await page.getByRole('button',{name:'舞台库',exact:true}).click()
    await page.locator('.stage-manual').getByRole('button',{name:'撤销',exact:true}).click()
    await until(read,s=>Object.values(s.graph.nodes).filter(n=>n.metadata.stageKind).length===0)
    await page.locator('.stage-manual').getByRole('button',{name:'重做',exact:true}).click()
    await until(read,s=>Object.values(s.graph.nodes).filter(n=>n.metadata.stageKind).length===3)
    checks.push('One undo removes entire batch; redo restores all three')
    await page.getByRole('button',{name:'舞台口令',exact:true}).click()
    await page.getByRole('textbox',{name:'舞台口令',exact:true}).fill('把沙发向台后移半米')
    await page.getByRole('button',{name:'生成舞台方案',exact:true}).click()
    await page.getByRole('button',{name:'确认搭台',exact:true}).click()
    stored=await until(read,s=>Object.values(s.graph.nodes).some(n=>n.metadata.stageKind==='sofa' && Math.abs(n.position[2]+.5)<1e-6))
    checks.push('A follow-up command changes the same saved sofa without replacing its ID')
    await page.getByRole('textbox',{name:'舞台口令',exact:true}).fill('把沙发向右边移半米')
    await page.getByRole('button',{name:'生成舞台方案',exact:true}).click()
    assert.equal(await page.getByRole('button',{name:'确认搭台',exact:true}).isDisabled(),true)
    checks.push('Ambiguous right side cannot apply before clarification')
    await page.screenshot({path:path.join(output,'clarification.png')})
    assert.deepEqual(errors,[])
    fs.writeFileSync(path.join(output,'browser.json'),JSON.stringify({url:page.url(),checks,errors,failed},null,2))
    console.log(JSON.stringify({checks,errors,failed}))
  } catch(e) { await page.screenshot({path:path.join(output,'failure.png')}).catch(()=>{});fs.writeFileSync(path.join(output,'failure.json'),JSON.stringify({url:page.url(),checks,errors,failed,error:String(e)},null,2));throw e }
  finally {await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
