type EvalCase = {
  input: string
  expectedIntent: string
  expectedCapability: string
  expectedTarget: string[]
  expectedDirection: string | null
  expectedAmount: { degree: 'exact' | 'small'; meters?: number; degrees?: number } | null
  clarificationRequired: boolean
}
const build = (input: string, id: string): EvalCase => ({
  input,
  expectedIntent: 'ADD_SCENERY',
  expectedCapability: 'build',
  expectedTarget: [id],
  expectedDirection: null,
  expectedAmount: null,
  clarificationRequired: false,
})
const move = (
  input: string,
  target: string,
  direction: string,
  amount: EvalCase['expectedAmount'],
): EvalCase => ({
  input,
  expectedIntent: 'MOVE_SCENERY',
  expectedCapability: 'build',
  expectedTarget: [target],
  expectedDirection: direction,
  expectedAmount: amount,
  clarificationRequired: false,
})
const view = (
  input: string,
  intent: string,
  direction: string | null = null,
  amount: EvalCase['expectedAmount'] = null,
  target: string[] = [],
): EvalCase => ({
  input,
  expectedIntent: intent,
  expectedCapability: 'view',
  expectedTarget: target,
  expectedDirection: direction,
  expectedAmount: amount,
  clarificationRequired: false,
})
